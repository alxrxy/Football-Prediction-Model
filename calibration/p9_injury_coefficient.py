"""P9: is the NFL injury term applied at the right magnitude? Re-checked after P41.
Diagnosis only. Read-only.

    python calibration/p9_injury_coefficient.py <pbp_dir> calibration/2026-09-22_p9_injury_coefficient.md

Questions, gate and pass rules were fixed in calibration-log.md (2026-09-22,
"P9 scoped") before this ran. <pbp_dir> is P37's: pbp_<season>.parquet for
2015-2026 (see p37_edge_diagnosis.py for how to build it).

    Q1 magnitude   actual - baseline(no injury)   = a + beta     x term
    Q2 edge        actual + market_spread         = a + gamma    x term   (P9's logged test)
    Q3 market      -market_spread - baseline      = a + beta_mkt x term

The baseline is P37's exact replay of live Layer 1 plus HFA / rest / travel,
x wind. The term is the training file's injury_diff (rebuilt after P41) x wind,
as live applies wind to the sum. The pre-P41 term is regenerated by re-running
build_training._nfl_injury_features with the old slot-ranking key patched in.
"""
