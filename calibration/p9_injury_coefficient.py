WF_SEASONS = list(range(2019, 2026))
DET_BUF = "2026_02_DET_BUF"      # excluded from P9 evidence (P20 caveat, 2026-09-17)


# --- inputs -------------------------------------------------------------------

def regen(old_key: bool):
    """(season, week, team) -> (points, qb loss), scored by the training code."""
    real = F._share_or_default
    if old_key:   # the pre-P41 key: a known 0.0 falls through to the default
        F._share_or_default = lambda r: r.get("snap_share") or F.DEFAULT_SNAP_SHARE
    try:
        return build_training._nfl_injury_features(SEASONS)
    finally:
        F._share_or_default = real


def game_terms(inj, g):
    h, hq = inj.get((int(g["season"]), int(g["week"]), g["home_team"]), (0.0, 0.0))
    a, aq = inj.get((int(g["season"]), int(g["week"]), g["away_team"]), (0.0, 0.0))
    return h - a, aq - hq


def build(pbp, post, pre):
    full = pd.read_csv(HERE.parent / "data" / "training_nfl.csv")
    train = full[(full["season"] >= 2016) & (full["season"] <= 2025) & (full["week"] <= 18)
                 & full["market_spread"].notna()]
    gate = {"n": 0, "post_mismatch": 0, "post_max": 0.0, "pre_rows": 0, "pre_max": 0.0}
    for _, g in full.iterrows():      # the gate runs on the whole file, as P41's 20 rows were counted
        inj_post, qb_post = game_terms(post, g)
        inj_pre, _ = game_terms(pre, g)
        gate["n"] += 1
        dpost = abs(inj_post - g["injury_diff"]) + abs(qb_post - g["qb_loss_diff"])
        gate["post_max"] = max(gate["post_max"], dpost)
        gate["post_mismatch"] += dpost > 1e-9
        dpre = abs(inj_pre - g["injury_diff"])
        gate["pre_rows"] += dpre > 1e-9
        gate["pre_max"] = max(gate["pre_max"], dpre)
    cache, rows = {}, []
    for _, g in train.iterrows():
        key = (int(g["season"]), int(g["week"]))
        if key not in cache:
            cache[key] = p37.ratings(*key, pbp)
        rt = cache[key]
        h, a = rt.get(p37.CANON.get(g["home_team"], g["home_team"])), rt.get(p37.CANON.get(g["away_team"], g["away_team"]))
        if not h or not a:
            continue
        sit, wf = p37.situational(g)
        base = (sum(h.values()) - sum(a.values()) + sit) * wf
        inj_pre, _ = game_terms(pre, g)
        term = g["injury_diff"] * wf
        qb = QB_SCALE * g["qb_loss_diff"] * wf
        rows.append({"season": key[0], "week": key[1], "game_id": g["game_id"], "base": base,
                     "actual": g["target_margin"], "market": g["market_spread"],
                     "term": term, "term_pre": inj_pre * wf, "qb": qb, "nonqb": term - qb})
    d = pd.DataFrame(rows)
    d["resid"] = d["actual"] + d["market"]         # Q2: + => home beat the line
    d["y_mag"] = d["actual"] - d["base"]           # Q1
    d["y_mkt"] = -d["market"] - d["base"]          # Q3
    return d, gate


# --- statistics ----------------------------------------------------------------

def ols(d, y, xs):
    """OLS with intercept; returns {name: (coef, HC1 se)}."""
    X = np.column_stack([np.ones(len(d))] + [d[x].to_numpy(float) for x in xs])
    Y = d[y].to_numpy(float)
    XtX_inv = np.linalg.inv(X.T @ X)
    b = XtX_inv @ X.T @ Y
    e = Y - X @ b
    n, k = X.shape
    meat = (X * e[:, None]).T @ (X * e[:, None])
    cov = XtX_inv @ meat @ XtX_inv * n / (n - k)
    se = np.sqrt(np.diag(cov))
    return {name: (b[i], se[i]) for i, name in enumerate(["const"] + list(xs))}


def one_sided_p(coef, se):
    return 0.5 * math.erfc((coef / se) / math.sqrt(2))


def ci(c, s):
    return f"{c:+.3f} ({c - 1.96 * s:+.3f} to {c + 1.96 * s:+.3f})"


def brier(margin, actual):
    keep = actual != 0
    p = np.array([F.normal_cdf(m / SIGMA) for m in margin[keep]])
    return float(np.mean((p - (actual[keep] > 0)) ** 2))


def load_2026_safe():
    try:
        return p37.load_2026()
    except Exception as exc:  # noqa: BLE001
        say(f"_2026 predictions unavailable: {exc}_")
        return None


# --- report --------------------------------------------------------------------

def main():
    say("# P9 — the NFL injury term's coefficient, re-checked after P41 (diagnosis only)")
    say()
    say("Rules fixed in calibration-log.md (2026-09-22, \"P9 scoped\") before this ran.")
    say()
    print("regenerating injury terms (post-P41, then pre-P41)...")
    post, pre = regen(old_key=False), regen(old_key=True)
    pbp = p37.load_pbp()
    d, gate = build(pbp, post, pre)
    capped = sum(1 for v in post.values() if v[0] <= -F.INJURY_MAX_POINTS + 1e-9)

    say("## Gate 0 — inputs")
    say()
    g0a = gate["post_mismatch"] == 0
    g0b = gate["pre_rows"] == 20 and abs(gate["pre_max"] - 0.588) < 0.001
    table([["regenerated post-P41 matches training (every row, < 1e-9)",
            f"{gate['n'] - gate['post_mismatch']}/{gate['n']} (max diff {gate['post_max']:.2e})", "pass" if g0a else "FAIL"],
           ["pre-P41 differs on exactly the 20 logged rows, max 0.588",
            f"{gate['pre_rows']} rows, max {gate['pre_max']:.3f}", "pass" if g0b else "FAIL"]],
          ["check", "result", "verdict"])
    say()
    say(f"Games: **{len(d)}** (2016-2025, weeks <= 18, line present). Team-weeks at the 8.0 cap: "
        f"**{capped}** of {len(post)} scored (the QB / non-QB split is approximate only there).")
    say()
    say(f"Gate rows are the whole training file ({gate['n']}), as P41's 20 were counted; "
        f"{int((d.term - d.term_pre).abs().gt(1e-9).sum())} of the 20 fall inside the fit sample.")
    say()
    if not (g0a and g0b):
        say("**Gate 0 failed: stop.**")
        return

    # --- Q1 -----------------------------------------------------------------
    say("## Q1 — magnitude: actual - baseline(no injury) = a + beta x term")
    say()
    full = ols(d, "y_mag", ["term"])
    b, s = full["term"]
    m1 = abs(b - 1.0) > 1.96 * s
    rows = [["full sample 2016-25", len(d), ci(b, s), "**excludes 1.0**" if m1 else "includes 1.0"]]
    for y in range(2016, 2026):
        f = ols(d[d.season == y], "y_mag", ["term"])["term"]
        rows.append([str(y), int((d.season == y).sum()), ci(*f), ""])
    table(rows, ["sample", "n", "beta (95% CI)", "vs 1.0"])
    say()
    say(f"**M1: {'pass' if m1 else 'fail'}** — the live coefficient 1.0 is "
        f"{'outside' if m1 else 'inside'} the full-sample 95% CI.")
    say()

    say("### M2 — walk-forward: beta fitted on 2016..Y-1, applied to Y, against the live 1.0")
    say()
    wf_rows, better, pooled = [], 0, {"live": [], "wf": [], "actual": [], "m_live": [], "m_wf": []}
    for y in WF_SEASONS:
        bt = ols(d[d.season < y], "y_mag", ["term"])["term"][0]
        t = d[d.season == y]
        m_live, m_wf = t["base"] + t["term"], t["base"] + bt * t["term"]
        e_live, e_wf = (t["actual"] - m_live).abs(), (t["actual"] - m_wf).abs()
        dm = e_wf.mean() - e_live.mean()
        better += dm < 0
        pooled["live"] += list(e_live); pooled["wf"] += list(e_wf)
        pooled["actual"] += list(t["actual"]); pooled["m_live"] += list(m_live); pooled["m_wf"] += list(m_wf)
        wf_rows.append([str(y), len(t), f"{bt:.3f}", f"{e_live.mean():.3f}", f"{e_wf.mean():.3f}", f"{dm:+.3f}"])
    pl, pw = np.mean(pooled["live"]), np.mean(pooled["wf"])
    act = np.array(pooled["actual"])
    br_l, br_w = brier(np.array(pooled["m_live"]), act), brier(np.array(pooled["m_wf"]), act)
    wf_rows.append(["**pooled 2019-25**", len(pooled["live"]), "", f"{pl:.3f}", f"{pw:.3f}", f"**{pw - pl:+.3f}**"])
    table(wf_rows, ["season", "n", "beta (fit on prior)", "MAE at 1.0", "MAE at beta", "change"])
    say()
    d25 = float(wf_rows[-2][5])
    m2 = {"pooled >= 0.05": (pl - pw) >= 0.05, ">= 5/7 seasons": better >= 5,
          "2025 not worse": d25 <= 0, "Brier not worse": br_w <= br_l}
    table([[k, "pass" if v else "fail"] for k, v in m2.items()]
          + [["(detail)", f"improved {better}/7; Brier {br_l:.4f} -> {br_w:.4f}"]], ["M2 part", "verdict"])
    say()
    m2_ok = all(m2.values())
    verdict = ("miscalibrated and material: a change is worth proposing" if m1 and m2_ok
               else "statistically off, immaterial: no change" if m1
               else "consistent with 1.0: no change")
    say(f"**M2: {'pass' if m2_ok else 'fail'}. Q1 verdict: {verdict}.**")
    say()

    say("### M3 — component split (diagnostic): QB part and non-QB part, jointly")
    say()
    comp = ols(d, "y_mag", ["qb", "nonqb"])
    qb_n = int((d.qb.abs() > 1e-9).sum())
    table([["QB (6.0 x qb_loss_diff)", qb_n, ci(*comp["qb"])],
           ["non-QB (remainder)", int((d.nonqb.abs() > 1e-9).sum()), ci(*comp["nonqb"])]],
          ["component", "games non-zero", "beta (95% CI)"])
    say()
    say(f"Mean |term|: all {d.term.abs().mean():.2f}, QB part {d.qb.abs().mean():.2f}, non-QB {d.nonqb.abs().mean():.2f}.")
    say()

    say("### M4 — P41 sensitivity: full-sample beta, pre vs post")
    say()
    dp = d.copy(); dp["term"] = dp["term_pre"]
    bp, sp = ols(dp, "y_mag", ["term"])["term"]
    table([["pre-P41", ci(bp, sp)], ["post-P41", ci(b, s)], ["delta", f"{b - bp:+.4f}"]], ["", "beta"])
    say()
    say(f"**M4: {'as expected' if abs(b - bp) < 0.02 else 'LARGER THAN EXPECTED — investigate first'}** "
        f"(|delta| {abs(b - bp):.4f} vs the < 0.02 expectation).")
    say()

    # --- Q2 -----------------------------------------------------------------
    say("## Q2 — edge (P9's logged adoption test): actual + market_spread = a + gamma x term")
    say()
    nz = int((d.term.abs() > 1e-9).sum())
    g, gs = ols(d, "resid", ["term"])["term"]
    p = one_sided_p(g, gs)
    q2 = g > 0 and p < 0.05 and nz >= 100
    rows = [["full sample 2016-25", len(d), ci(g, gs), f"{p:.3f}"]]
    for y in range(2016, 2026):
        t = d[d.season == y]
        c, cs = ols(t, "resid", ["term"])["term"]
        rows.append([str(y), len(t), ci(c, cs), f"{one_sided_p(c, cs):.3f}"])
    table(rows, ["sample", "n", "gamma (95% CI)", "one-sided p"])
    say()
    cq = ols(d, "resid", ["qb", "nonqb"])
    table([["QB", ci(*cq["qb"]), f"{one_sided_p(*cq['qb']):.3f}"],
           ["non-QB", ci(*cq["nonqb"]), f"{one_sided_p(*cq['nonqb']):.3f}"]],
          ["component (joint)", "gamma (95% CI)", "one-sided p"])
    say()
    fires = d[d.qb.abs() > 1e-9]
    say(f"Cross-check with P28's re-test: corr(QB part, cover residual) = {np.corrcoef(d.qb, d.resid)[0, 1]:+.3f} "
        f"over all {len(d)} games, {np.corrcoef(fires.qb, fires.resid)[0, 1]:+.3f} over the {len(fires)} where it fires. "
        f"2024-25 only: {np.corrcoef(d[d.season >= 2024].qb, d[d.season >= 2024].resid)[0, 1]:+.3f}.")
    say()
    say(f"**Q2: {'pass' if q2 else 'fail'}** (gamma {g:+.3f}, one-sided p {p:.3f}, {nz} games with a non-zero term).")
    say()

    # --- Q3 -----------------------------------------------------------------
    say("## Q3 — market-implied size: -market_spread - baseline = a + beta_mkt x term (descriptive)")
    say()
    bm = ols(d, "y_mkt", ["term"])["term"]
    cm = ols(d, "y_mkt", ["qb", "nonqb"])
    table([["term", ci(*bm)], ["QB part (joint)", ci(*cm["qb"])], ["non-QB part (joint)", ci(*cm["nonqb"])]],
          ["", "beta_mkt (95% CI)"])
    say()

    # --- 2026 ---------------------------------------------------------------
    say("## 2026 weeks 1-2, descriptive only (stored terms, pre-P20/P41/P10)")
    say()
    d26 = load_2026_safe()
    if d26 is not None and len(d26):
        d26 = d26[d26.game_id != DET_BUF]
        noinj = d26["edge"] - d26["market"] - d26["inj_part"]      # model margin without the term
        r_mag = d26["actual"] - noinj
        table([["games", len(d26)],
               ["mean |term|", f"{d26.inj_part.abs().mean():.2f}"],
               ["corr(term, cover residual)", f"{np.corrcoef(d26.inj_part, d26.resid)[0, 1]:+.3f}"],
               ["corr(term, actual - no-injury margin)", f"{np.corrcoef(d26.inj_part, r_mag)[0, 1]:+.3f}"],
               ["beta (in-sample, no decision)", ci(*ols(d26.assign(y=r_mag), "y", ["inj_part"])["inj_part"])]],
              ["", "value"])
    say()


if __name__ == "__main__":
    main()
    if OUT:
        OUT.write_text("\n".join(p37.lines) + "\n", encoding="utf-8")
        print(f"\nwrote {OUT}")
